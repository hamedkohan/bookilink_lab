def demo_debate(book_a_key: str, book_b_key: str, question: str) -> tuple[str, list[dict]]:
    a = DEMO_BOOKS[book_a_key]
    b = DEMO_BOOKS[book_b_key]
    answer = f"""## Position A — {a['title']}\n{a['title']} مسئله را از سمت **سیستم رفتاری** می‌بیند: اگر رفتار ارزشمند نتواند به یک الگوی تکرارشونده تبدیل شود، insight خوب هم به outcome پایدار نمی‌رسد. [A1][A2]\n\n## Position B — {b['title']}\n{b['title']} روی **انتخاب نوع رفتار و کیفیت تصمیم** تأکید می‌کند: همه عادت‌ها یا همه ساعت‌های کار ارزش یکسان ندارند؛ باید بدانیم کجا تمرکز، ریسک یا تصمیم بیشترین leverage را دارد. [B1][B2]\n\n## Where they actually disagree\nاختلاف اصلی بر سر «مکانیزم» در برابر «اولویت» است؛ یکی بیشتر می‌پرسد رفتار چگونه پایدار می‌شود، دیگری می‌پرسد کدام رفتار/تصمیم ارزش پایدار کردن دارد.\n\n## Synthesis\nبرای سؤال «{question}» پاسخ قوی‌تر ترکیبی است: اول رفتار با leverage بالا را تشخیص بده، بعد آن را به سیستم تکرارشونده تبدیل کن. مناظره نشان می‌دهد این دو کتاب بیشتر مکمل‌اند تا رقیب.\n"""
    sources: list[dict] = []
    for prefix, book in (("A", a), ("B", b)):
        for i, (_, locator, text) in enumerate(book["sources"][:2], start=1):
            sources.append({"label": f"{prefix}{i}", "locator": locator, "score": 0.9 - i * 0.05, "text": text})
    return answer, sources
